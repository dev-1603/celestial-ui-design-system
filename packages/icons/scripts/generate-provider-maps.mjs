#!/usr/bin/env node
/**
 * Build-time provider data for browser-safe Lucide + Heroicons adapters.
 *
 * Reads the canonical mapping catalogues and inlines only those glyphs from
 * optional peers (devDependencies during this package's build). Runtime
 * adapters import the generated maps — no Node fs and no full-pack require.
 */
import { createRequire } from 'node:module';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const iconsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = path.join(iconsRoot, 'src/providers/generated');
const lucideCataloguePath = path.join(iconsRoot, 'src/data/mappings/lucide.json');
const heroiconsCataloguePath = path.join(iconsRoot, 'src/data/mappings/heroicons.json');

const HEROICON_STYLES = [
  { style: 'outline', relative: (stem) => `24/outline/${stem}.svg` },
  { style: 'solid', relative: (stem) => `24/solid/${stem}.svg` },
  { style: 'mini', relative: (stem) => `20/solid/${stem}.svg` },
  { style: 'micro', relative: (stem) => `16/solid/${stem}.svg` },
];

const UPPER_RE = /[A-Z]/;
const LOWER_RE = /[a-z]/;

/**
 * Splits an acronym run from the word that follows it, e.g. "ABCDef" ->
 * "ABC-Def". Implemented as a manual scan (rather than the equivalent
 * `/([A-Z]+)([A-Z][a-z])/` regex) because two adjacent quantified groups over
 * the overlapping `[A-Z]` character class have super-linear backtracking
 * behavior on pathological all-uppercase input (typescript:S8786-flagged
 * shape) even when rewritten with a lookahead.
 * @param {string} value
 */
function splitAcronymBoundary(value) {
  let result = '';
  let i = 0;
  while (i < value.length) {
    if (!UPPER_RE.test(value[i])) {
      result += value[i];
      i += 1;
      continue;
    }
    let j = i;
    while (j < value.length && UPPER_RE.test(value[j])) j += 1;
    const runLength = j - i;
    const nextIsLower = j < value.length && LOWER_RE.test(value[j]);
    if (runLength >= 2 && nextIsLower) {
      result += `${value.slice(i, j - 1)}-${value.slice(j - 1, j)}`;
    } else {
      result += value.slice(i, j);
    }
    i = j;
  }
  return result;
}

function toAssetStem(nativeName) {
  if (/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(nativeName)) return nativeName;
  return splitAcronymBoundary(nativeName)
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .replace(/(\d)([A-Z])/g, '$1-$2')
    .toLowerCase();
}

function uniqueNativeNames(cataloguePath) {
  const catalogue = JSON.parse(fs.readFileSync(cataloguePath, 'utf8'));
  const names = [];
  const seen = new Set();
  for (const entry of catalogue.entries ?? []) {
    const nativeName = entry.nativeName;
    if (typeof nativeName !== 'string' || seen.has(nativeName)) continue;
    seen.add(nativeName);
    names.push(nativeName);
  }
  names.sort((a, b) => a.localeCompare(b));
  return { providerVersion: catalogue.providerVersion, names };
}

function writeGenerated(fileName, body) {
  fs.mkdirSync(generatedDir, { recursive: true });
  const header =
    '/* GENERATED by scripts/generate-provider-maps.mjs — do not edit. */\n';
  fs.writeFileSync(path.join(generatedDir, fileName), `${header}${body}`);
}

function generateLucideMap() {
  const { providerVersion, names } = uniqueNativeNames(lucideCataloguePath);
  const lucide = require('lucide-static');
  const missing = names.filter((name) => typeof lucide[name] !== 'string');
  if (missing.length > 0) {
    throw new Error(
      `[generate-provider-maps] lucide-static is missing catalogue natives: ${missing.join(', ')}`,
    );
  }

  const entries = names
    .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(lucide[name])},`)
    .join('\n');

  writeGenerated(
    'lucide-catalogue-svgs.ts',
    `export const LUCIDE_CATALOGUE_VERSION = ${JSON.stringify(providerVersion)} as const;\n\n` +
      '/** Canonical Lucide natives only. Runtime name lookup cannot per-call DCE. */\n' +
      'export const LUCIDE_SVG_BY_NATIVE_NAME: Readonly<Record<string, string>> = {\n' +
      `${entries}\n};\n`,
  );
  console.log(`wrote lucide-catalogue-svgs.ts (${names.length} natives)`);
}

function generateHeroiconsMap() {
  const { providerVersion, names } = uniqueNativeNames(heroiconsCataloguePath);
  const heroRoot = path.dirname(require.resolve('heroicons/package.json'));
  /** @type {Record<string, Record<string, string>>} */
  const map = {};
  const missingNatives = [];

  for (const nativeName of names) {
    const stem = toAssetStem(nativeName);
    /** @type {Record<string, string>} */
    const styles = {};
    for (const { style, relative } of HEROICON_STYLES) {
      const filePath = path.join(heroRoot, relative(stem));
      if (!fs.existsSync(filePath)) continue;
      styles[style] = fs.readFileSync(filePath, 'utf8');
    }
    if (Object.keys(styles).length === 0) {
      missingNatives.push(`${nativeName} (${stem}.svg)`);
      continue;
    }
    map[nativeName] = styles;
  }

  if (missingNatives.length > 0) {
    throw new Error(
      `[generate-provider-maps] heroicons is missing catalogue natives:\n${missingNatives.join('\n')}`,
    );
  }

  writeGenerated(
    'heroicons-catalogue-svgs.ts',
    `export const HEROICONS_CATALOGUE_VERSION = ${JSON.stringify(providerVersion)} as const;\n\n` +
      "export type HeroiconsStyle = 'outline' | 'solid' | 'mini' | 'micro';\n\n" +
      '/** Canonical Heroicons natives × style. No Node fs at runtime. */\n' +
      'export const HEROICONS_SVG_BY_NATIVE_AND_STYLE: Readonly<\n' +
      '  Record<string, Partial<Record<HeroiconsStyle, string>>>\n' +
      `> = ${JSON.stringify(map, null, 2)} as const;\n`,
  );
  console.log(`wrote heroicons-catalogue-svgs.ts (${names.length} natives)`);
}

generateLucideMap();
generateHeroiconsMap();
